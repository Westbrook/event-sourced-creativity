import {readFile} from 'node:fs/promises';
import {iapVerifier} from './identity.mjs';
import {poolFromEnvironment} from './database.mjs';
import {CoreRepository} from './core-repository.mjs';
import {createCoreServer} from './core-http.mjs';
const pool=poolFromEnvironment();
const encryptionRoot=await readFile(process.env.PILOT_ENCRYPTION_ROOT_FILE,'utf8');
const repository=new CoreRepository(pool,{encryptionRoot:encryptionRoot.trim(),expiresAt:process.env.PILOT_EXPIRES_AT});
const origin=process.env.PILOT_ORIGIN;if(!origin||!origin.startsWith('https://'))throw Error('https_pilot_origin_required');
const server=createCoreServer({repository,verify:iapVerifier({audience:process.env.PILOT_IAP_AUDIENCE}),origin,sourceCommit:process.env.SOURCE_COMMIT});
server.listen(Number(process.env.PORT??8080),process.env.PILOT_BIND??'127.0.0.1');
process.on('SIGTERM',()=>server.close(async()=>{await pool.end();process.exit(0);}));
