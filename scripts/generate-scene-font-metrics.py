"""Build-time extraction from the pinned, unmodified font. No network/install.

Run with FontTools 4.65.0. The generated table is a deliberately conservative
simple-text profile, not a substitute for a Unicode shaping engine.
"""
import hashlib
import json
import itertools
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "public/fonts/dm-mono/DMMono-Regular-55b4c98f.ttf"
FONT_SHA = "55b4c98f123daebb3ed27947ba47b2af00554fc6284d639a540bcef5e6258ad2"
data = FONT.read_bytes()
assert len(data) == 49744 and hashlib.sha256(data).hexdigest() == FONT_SHA
# Printable ASCII plus NBSP, literal cue separator and ordinary typographic
# punctuation. Combining marks, joiners, complex scripts and substitutions are
# never silently flattened to this profile.
points = list(range(32, 127)) + [160, 183, 8211, 8212, 8216, 8217, 8218, 8220, 8221, 8222, 8230]
with TTFont(FONT) as font:
    assert font["head"].unitsPerEm == 1000
    cmap = font.getBestCmap()
    metrics = {}
    for point in points:
        name = cmap[point]
        glyph = font["glyf"][name]
        glyph.recalcBounds(font["glyf"])
        advance = font["hmtx"][name][0]
        assert advance == 600
        bounds = [glyph.xMin, glyph.yMin, glyph.xMax, glyph.yMax] if glyph.numberOfContours else [0, 0, 0, 0]
        metrics[str(point)] = [advance, *bounds]
    # This profile must not complete an active default GSUB context, including
    # localized Latin substitutions. Optional stylistic features are off.
    approved = {cmap[point] for point in points}
    forbidden_sequences = set()
    reverse = {cmap[point]: chr(point) for point in points}
    table = font["GSUB"].table
    for feature in table.FeatureList.FeatureRecord:
        if feature.FeatureTag not in ("ccmp", "locl", "rlig", "liga", "clig", "calt"):
            continue
        for index in feature.Feature.LookupListIndex:
            for subtable in table.LookupList.Lookup[index].SubTable:
                if hasattr(subtable, "mapping"):
                    assert not approved.intersection(subtable.mapping)
                else:
                    coverages = (getattr(subtable, "BacktrackCoverage", [])
                                 + getattr(subtable, "InputCoverage", [])
                                 + getattr(subtable, "LookAheadCoverage", []))
                    assert coverages
                    matches = [sorted(approved.intersection(coverage.glyphs)) for coverage in coverages]
                    if all(matches):
                        assert all(len(match) == 1 for match in matches)
                        forbidden_sequences.update("".join(reverse[glyph] for glyph in sequence) for sequence in itertools.product(*matches))
    # The font has mark positioning only; this profile has no combining marks.
    assert {record.FeatureTag for record in font["GPOS"].table.FeatureList.FeatureRecord} <= {"mark", "mkmk"}

payload = {"profile": "dm-mono-simple-text-v1", "fontSha256": FONT_SHA, "fontBytes": len(data), "unitsPerEm": 1000, "forbiddenSequences": sorted(forbidden_sequences), "glyphs": metrics}
canonical = json.dumps(payload, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
digest = hashlib.sha256(canonical.encode()).hexdigest()
output = ("// Generated by scripts/generate-scene-font-metrics.py; do not edit.\n"
          "// Tuple: advance, xMin, yMin, xMax, yMax in font units.\n"
          f"export const SCENE_FONT_METRICS_SHA256 = {json.dumps(digest)};\n"
          f"export const SCENE_FONT_METRICS = {canonical} as const;\n")
(ROOT / "worker/scene-font-metrics.ts").write_text(output)
print(json.dumps({"profile": payload["profile"], "glyphs": len(metrics), "metricsSha256": digest, "fontSha256": FONT_SHA}))
