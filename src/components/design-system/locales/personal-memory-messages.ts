/** Component-owned catalog: no activation flag or shared locale-registration mutation. */
export function personalMemoryMessage(locale: string, key: string, values: Record<string, string | number> = {}): string {
  const family = locale.toLowerCase().split("-")[0];
  const catalog: Readonly<Record<string, string>> = family === "fr" ? FORMA_PERSONAL_MEMORY_MESSAGES.fr
    : family === "ar" ? FORMA_PERSONAL_MEMORY_MESSAGES.ar : family === "ja" ? FORMA_PERSONAL_MEMORY_MESSAGES.ja
      : FORMA_PERSONAL_MEMORY_MESSAGES.en;
  const message = catalog[key] ?? (FORMA_PERSONAL_MEMORY_MESSAGES.en as Readonly<Record<string, string>>)[key] ?? key;
  return message.replace(/\{(\w+)\}/gu, (_, name: string) => String(values[name] ?? ""));
}
