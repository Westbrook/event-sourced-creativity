/**
 * Explicit synthetic store/adapter bridge, NOT FormaStore.reconcileOutputOperationReceipt.
 * The real method owns private #jobDetails and has separate actual-method tests.
 * This bridge only lets the real controller exercise its receipt UI with in-memory replies.
 */
export async function reconcileOutputFixtureReceipt({ adapter, client, documentId, grantId, slotId, jobId, notify = () => {} }) {
  const scope = adapter.scope();
  const active = () => adapter.scopeActive(scope);
  const forbidden = () => ({ status: "forbidden", errorCode: "output_receipt_scope_changed" });
  const resource = client.resource(documentId), snapshot = resource.snapshot;
  const grant = snapshot?.grants.find((row) => row.id === grantId);
  const slot = grant?.operations.find((row) => row.id === slotId && row.jobId === jobId);
  if (!active() || resource.state !== "ready" || snapshot?.documentId !== documentId || snapshot.projectId !== scope?.projectId
    || !grant || !slot || grant.actorUserId !== snapshot.scope.actorUserId) return forbidden();
  try {
    // A local adapter endpoint, not global fetch, guardedFetch, a provider lookup, or a queue driver.
    const response = await adapter.fetch(`/api/document-jobs/${encodeURIComponent(jobId)}/reconcile-output`, { method: "POST" });
    if (!active()) return forbidden();
    const body = await response.json();
    if (!active()) return forbidden();
    if (!response.ok) return [401, 403, 404].includes(response.status) ? forbidden() : { status: "invalid", errorCode: "output_receipt_check_failed" };
    const receipt = body.reconciliation;
    if (!body.job || body.job.jobId !== jobId || body.job.documentId !== documentId || !["generate", "render_document"].includes(body.job.kind)
      || !["completed", "partial", "failed", "canceled"].includes(body.job.status)
      || !receipt || receipt.documentId !== documentId || receipt.grantId !== grantId || receipt.slotId !== slotId || receipt.jobId !== jobId
      || !["known", "uncertain", "not_needed"].includes(receipt.status) || typeof receipt.reconciled !== "boolean") return { status: "invalid", errorCode: "output_receipt_response_mismatch" };
    const current = await client.ensure(documentId, { force: true });
    if (!active() || current.accessLost) return forbidden();
    if (current.state === "ready" && (current.snapshot?.documentId !== documentId || current.snapshot.projectId !== scope.projectId
      || !current.snapshot.grants.some((row) => row.id === grantId && row.operations.some((entry) => entry.id === slotId && entry.jobId === jobId)))) return { status: "invalid", errorCode: "output_receipt_response_mismatch" };
    // Fixture job reads derive from the adapter; no borrowed private field or job-sync method is used.
    notify();
    return { status: receipt.status, reconciled: receipt.reconciled, refreshed: current.state === "ready" };
  } catch { return active() ? { status: "unavailable", errorCode: "output_receipt_check_failed" } : forbidden(); }
}

