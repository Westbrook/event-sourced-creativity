test('current review expires at each owned hash boundary, including acknowledgement validation',async()=>{
  for(const phase of ['read','prepare','ack'])for(const expireAfter of phase==='read'?[1]:[1,2]){
    const{now,identity,shown,request}=await fixture(),message=await prepareSponsorAudioAuthorize(shown,request),ack=acknowledgment(shown,message);
    const clock=Date.now,subtle=crypto.subtle,hash=subtle.digest;let calls=0;
    Date.now=()=>now;
    subtle.digest=async function(...args){const result=await hash.apply(this,args);if(++calls===expireAfter)Date.now=()=>Date.parse(shown.review.expiresAt);return result;};
    try{await assert.rejects(phase==='read'?readSponsorAudioReviewResponse(shown,identity):phase==='prepare'?prepareSponsorAudioAuthorize(shown,request):readSponsorAudioAuthorizationResponse(ack,shown,message));}
    finally{Date.now=clock;subtle.digest=hash;}
    assert.equal(calls,expireAfter);
  }
  const{identity,shown}=await fixture(),clock=Date.now;
  try{Date.now=()=>NaN;await assert.rejects(readSponsorAudioReviewResponse(shown,identity));}finally{Date.now=clock;}
});

