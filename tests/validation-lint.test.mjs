const lint = (source, sourceType = 'module') => new Linter().verify(source, { languageOptions: { sourceType, globals: { eval: 'readonly' } }, plugins: { harness: { rules: { 'eval-scope': evalScope } } }, rules: { 'no-unused-vars': 'error', 'harness/eval-scope': 'error' } });
test('dynamic harness scope is visible to real eval but unrelated unused locals still fail', () => {
  assert.deepEqual(lint('const importedContract=1; eval("importedContract");'), []);
  assert.equal(lint('export function a(){ const unused=1; } eval("a");').filter(m => m.ruleId === 'no-unused-vars').length, 1);
  assert.equal(lint('function a(eval){ const unused=1; eval("unused"); } a(()=>{});', 'script').filter(m => m.ruleId === 'no-unused-vars').length, 1);
});
function fixture(t) {
  const root=mkdtempSync(join(tmpdir(),'forma-lint-'));
  t.after(()=>rmSync(root,{recursive:true,force:true}));
  const put=(file,data)=>{const path=join(root,file);mkdirSync(join(path,'..'),{recursive:true});writeFileSync(path,data);};
  return {root,put};
}
test('vendor integrity rejects altered generated bytes and unrecorded modules', t => {
  const {root,put}=fixture(t),base='src/still/vendor/';
  put(base+'a.js','export const a=1;');put(base+'tokens/default.css',':root{}');
  const outputClosureSha256=createHash('sha256').update('a.js').update('export const a=1;').update('tokens/default.css').update(':root{}').digest('hex');
  put(base+'provenance.json',JSON.stringify({revision:'upstream',modules:1,modulePaths:['a.js'],outputClosureSha256}));
  assert.equal(verifyVendor(root).modules,1);
  put(base+'a.js','export const a=2;');assert.throws(()=>verifyVendor(root),/Vendored bytes/);
  put(base+'b.js','');assert.throws(()=>verifyVendor(root),/membership changed/);
});
test('browser orphans fail inventory ownership; optional inputs are discovered without executing them', t => {
  const {root,put}=fixture(t);
  put('package.json','{"scripts":{}}');put('tests/browser/a.spec.mjs','if(process.env.PRIVATE_ARCHIVE) throw Error("must not execute");');
  const current=census(root),tests={'tests/browser/a.spec.mjs':'browser'};
  assert.throws(()=>executionOwnership(root,current,tests),/Unowned browser/);
  put('playwright.a.config.mjs',"export default {testMatch:'a.spec.mjs'};");
  const next=census(root);assert.equal(executionOwnership(root,next,tests)['tests/browser/a.spec.mjs'].configs[0],'playwright.a.config.mjs');
  assert.deepEqual(environmentInputs(root,next)[0].flags,['PRIVATE_ARCHIVE']);
});

test('compiled fixture code reuses exact inputs without sharing module state', async () => {
  const {fixtureCode,fixtureCodeStats}=await import('./helpers/fixture-code.mjs');
  const source='export let n=0; export function increment(){ return ++n; }',options={target:9,module:1};
  const code=fixtureCode(source,options),before=fixtureCodeStats();
  assert.equal(fixtureCode(source,options),code);assert.equal(fixtureCodeStats().hits,before.hits+1);
  const first={},second={};new Function('exports',code)(first);new Function('exports',code)(second);
  assert.equal(first.increment(),1);assert.equal(first.increment(),2);assert.equal(second.increment(),1);
  assert.notEqual(fixtureCode(source.replace('n=0','n=20'),options),code);
  assert.notEqual(fixtureCode(source,{...options,module:99}),code);
  assert.ok(fixtureCodeStats().bytes<=fixtureCodeStats().maximumBytes);
});
