import assert from "node:assert/strict";
import test from "node:test";
import fs from "node:fs";
import { registerHooks } from "node:module";
import { pathToFileURL } from "node:url";
import { createHash } from "node:crypto";
const root = new URL("../", import.meta.url);
const fixtureUrl = pathToFileURL(fs.realpathSync(new URL("tests/scene-cost-composer.test.mjs", root)));
const fixtureSource = fs.readFileSync(fixtureUrl, "utf8");
const stop = fixtureSource.indexOf('for(const locale of ["en","fr","ar","ja"])');
assert.ok(stop > 0);
const virtual = fixtureUrl.href + "?native-scene-completion-join";
const hook = registerHooks({ load(url, context, next) {
  return url === virtual ? {format:"module", source:fixtureSource.slice(0, stop)+"\nexport { action, enabled, settle };\n", shortCircuit:true} : next(url, context);
}});
const {createSceneComposer,action,enabled,settle} = await import(virtual).finally(()=>hook.deregister());
const {createSceneCostFixture} = await import(new URL("tests/helpers/scene-cost-fixture.mjs",root));
const {createSceneStoreHost} = await import(new URL("tests/helpers/scene-cost-store-host.mjs",root));
const {scenePilotProvider} = await import(new URL("tests/helpers/scene-pilot-fixture.mjs",root));

test("native Scene: acknowledged Document Save and explicit one-job completion bind original result without discarding drafts", async t => {
  const worker = await createSceneCostFixture(1,"visual");
  const h = await createSceneStoreHost({workerFixture:worker, exposeSceneTestAccessors:false});
  h.store.patchUi({instrumentation:false});
  const pending = new Set(), replies = [];
  h.transport = async request => { const task = worker.request(request.url,request.init); pending.add(task); try{const response=await task;replies.push({request,status:response.status,body:await response.clone().json()});return response;}finally{pending.delete(task);} };
  const providerCalls = scenePilotProvider(t);
  const providerFetch = globalThis.fetch;
  let forbiddenRequests = [];
  t.mock.method(globalThis,"fetch",async (url,init) => {
    if(String(url).startsWith("/api/")) return h.fetch(url,init);
    if(String(url)==="https://api.openai.com/v1/responses") return providerFetch(url,init);
    forbiddenRequests.push(String(url));throw new Error("No external provider/network allowed");
  });
  let f;
  t.after(async()=>{
    while(pending.size)await Promise.allSettled([...pending]);
    await worker.drainBackground();
    if(f){f.host.isConnected=false;f.host.disconnectedCallback();f.i18n.hostDisconnected();}
    await h.close();assert.deepEqual(forbiddenRequests,[]);
  });
  const savedText="The keeper verifies the harbor chart before opening the lantern room.\n\nوفحصت ميرا الضوء قبل الفجر.";
  const beforeJobs=worker.sqlite.prepare("SELECT COUNT(*) AS n FROM document_jobs").get().n;
  const saved=await h.store.saveBlockText("scene-reuse-direction",savedText,"document-context-editor");
  assert.equal(saved.length,1,"one actual acknowledged Document context Save");
  assert.equal(saved[0].type,"BlockPropertyEdited");
  assert.equal(saved[0].payload.new_value,savedText);
  assert.equal(h.store.projection.get().libraryBlocks.find(b=>b.id==="scene-reuse-direction").properties.text,savedText);
  assert.equal(worker.sqlite.prepare("SELECT COUNT(*) AS n FROM document_jobs").get().n,beforeJobs,"Save never creates a job");
  assert.equal(providerCalls.length,0,"Save never invokes provider transport");
  f=await createSceneComposer(t,{storeHost:h,count:1});f.state.documentId=worker.documentId;
  await f.openScene({mode:"manual"});await f.check();
  const quote=h.requests.find(r=>r.url==="/api/document-jobs"&&r.body?.payload?.sceneCostPreview===true);
  assert.ok(quote,"actual free quote request");
  assert.equal(providerCalls.length,0,"quote never invokes provider transport");
  await f.submit();
  const deadline=performance.now()+5000;
  while(!replies.some(r=>r.request.body?.payload?.sceneCostConsent?.confirmed===true)&&performance.now()<deadline)await new Promise(resolve=>setTimeout(resolve,1));
  await settle(f);
  const admittedReply=replies.find(r=>r.request.body?.payload?.sceneCostConsent?.confirmed===true);
  assert.ok(admittedReply,"await the actual async Scene admission reply");
  assert.ok(admittedReply.status===200||admittedReply.status===202,JSON.stringify(admittedReply.body));
  const admissions=h.requests.filter(r=>r.url==="/api/document-jobs"&&r.body?.payload?.sceneCostConsent?.confirmed===true);
  assert.equal(admissions.length,1,"one explicit admitted request");
  const requestId=admittedReply.body.job.jobId;
  assert.equal(requestId,admissions[0].body.payload.sceneRequestId);
  assert.equal(admissions[0].body.documentId,worker.documentId);
  const submitted=admissions[0].body.payload;
  const savedFact=submitted.snapshot.facts.find(fact=>fact.block_id==="scene-reuse-direction");
  assert.equal(savedFact.properties.text,savedText,"the acknowledged Document text is the submitted source");
  assert.ok(savedFact.source_event_refs.includes(saved[0].eventId),"the saved source event remains in the request witness");
  assert.deepEqual(submitted.sourceBlockVersions,[{block_id:"scene-reuse-direction",version:2}]);
  assert.equal(admittedReply.body.job.documentRevision,submitted.documentRevision,"the acknowledged job keeps that exact Document revision");
  const jobBefore=worker.sqlite.prepare("SELECT * FROM document_jobs WHERE job_id=?").get(requestId);assert.ok(jobBefore);
  const run=await worker.run(requestId);
  assert.equal(run.response.status,200,JSON.stringify(run.body));
  const job=worker.sqlite.prepare("SELECT * FROM document_jobs WHERE job_id=?").get(requestId);
  assert.equal(job.status,"completed",JSON.stringify(run.body));
  assert.equal(providerCalls.length,1,"one declared in-memory Responses result; no real provider");
  const result=JSON.parse(job.result_json);
  const completions=worker.sqlite.prepare("SELECT * FROM events WHERE correlation_id=? AND type='DocumentRenderCompleted'").all(job.correlation_id);assert.equal(completions.length,1);
  const completed=JSON.parse(completions[0].payload);
  const raw=worker.sqlite.prepare("SELECT content FROM private_content WHERE content_id=?").get(completed.content_ref).content;
  assert.equal(h.store.projection.get().libraryArtifacts.some(artifact=>artifact.id===result.artifactId),false,
    "the completed receipt is not yet present in the existing local projection");
  const originalSource=h.store.captureSceneCostSource({requestId,documentId:worker.documentId,
    sceneMedium:submitted.sceneMedium,productionMode:submitted.productionMode,audience:submitted.audience,tone:submitted.tone,locale:submitted.locale});
  assert.equal(originalSource(),true);
  await h.store.refreshEvents({readOnly:true,current:originalSource});
  assert.equal(originalSource(),true,"completion-only refresh preserves the exact original Scene input guard");
  assert.equal(h.store.projection.get().libraryArtifacts.find(artifact=>artifact.id===result.artifactId)?.documentId,worker.documentId,
    "guarded refresh supplies the exact retained reader artifact prerequisite");
  await f.openScene({mode:"manual"});await f.check();
  const open=action(f,"scene.cost.openOriginal");
  const {nativeSceneCompletionPath,nativeSceneRetainedRoute,validateNativeSceneCompletion}=await import(new URL("src/model/native-scene-completion.ts",root));
  const {parseNativeRetainedOutputRoute,nativeRetainedOutputRequestPath}=await import(new URL("src/model/native-retained-output.ts",root));
  const ownerRow=worker.sqlite.prepare("SELECT user_id,email FROM users WHERE user_id=?").get(worker.owner);
  const trustedTestHeaders={"oai-authenticated-user-id":ownerRow.user_id,"oai-authenticated-user-email":ownerRow.email};
  const handle={documentId:worker.documentId,jobId:requestId};
  const completionReply=await worker.request(nativeSceneCompletionPath(handle),{headers:trustedTestHeaders});
  const completionBody=await completionReply.json();
  assert.equal(completionReply.status,200,JSON.stringify(completionBody));
  const receipt=validateNativeSceneCompletion(completionBody,handle);assert.ok(receipt);
  const nativeRoute=nativeSceneRetainedRoute(receipt,handle),selection=parseNativeRetainedOutputRoute(nativeRoute);
  assert.deepEqual(selection,{output:"scene",selection:{documentId:worker.documentId,artifactId:result.artifactId,revision:0,contentSha256:createHash("sha256").update(raw).digest("hex")}});
  const nativeRead=await worker.request(nativeRetainedOutputRequestPath(selection),{headers:trustedTestHeaders});
  assert.equal(nativeRead.status,200,await nativeRead.clone().text());
  const nativeBody=await nativeRead.json();assert.equal(nativeBody.content.content_markdown,JSON.parse(raw).content_markdown);
  assert.equal(providerCalls.length,1,"completion/read performs no extra provider work");
  const record={scope:"Actual Document context Save, production Scene composer/Store/Worker in RAM; deterministic declared provider reply only; authoritative completion-link and enabled native Open verified; native browser navigation remains pending",savedEventId:saved[0].eventId,savedDocumentId:worker.documentId,requestId,jobStatus:job.status,artifactId:result.artifactId,completionEventId:completions[0].event_id,revision:0,rawContentSha256:createHash("sha256").update(raw).digest("hex"),providerReplyCount:providerCalls.length,actualJobCount:worker.sqlite.prepare("SELECT COUNT(*) AS n FROM document_jobs").get().n,nativeRoute,completionReceipt:receipt,openButtonPresent:Boolean(open),originalRequestCopy:f.visible().includes("Original Scene request")};
  t.diagnostic(JSON.stringify(record));
  assert.ok(enabled(open),"explicit Open original Scene from checked completed original request");
  const fill=async(field,value)=>{const node=f.renderer.ownNodes(f.host,"input").find(n=>n.attributes.name===field);assert.ok(node,"current named guidance input");node.value=value;await node.handlers.input.call(f.host,{target:node,currentTarget:node});await f.flush();};
  await fill("audience","A future draft audience");await f.check();
  assert.equal(enabled(action(f,"scene.cost.openOriginal")),false,"a later checked draft cannot replace the original result");
  assert.ok(enabled(action(f,"scene.cost.receipt")),"original input inspection remains available for a different draft");
  await fill("audience"," ");await f.check();
  assert.equal(enabled(action(f,"scene.cost.openOriginal")),false,"raw whitespace edits remain a draft even if normalized request hash matches");
  await fill("audience","");await f.check();
  assert.ok(enabled(action(f,"scene.cost.openOriginal")),"restoring the exact original settings restores Open");
  const pickKind=async kind=>{const node=f.renderer.ownNodes(f.host,"input").find(n=>n.attributes.name==="artifact-kind"&&n.attributes.value===kind);assert.ok(node);await node.handlers.change.call(f.host,{target:node,currentTarget:node});await f.flush();};
  await pickKind("slides");await fill("audience","Keep this presentation draft");await pickKind("scene");await f.check();
  assert.equal(enabled(action(f,"scene.cost.openOriginal")),false,"a cached draft for another output kind blocks route replacement");
  assert.ok(enabled(action(f,"scene.cost.receipt")),"original inspection remains usable with another retained draft");
  assert.equal(providerCalls.length,1,"guard checks perform no additional provider work");
  assert.equal(worker.sqlite.prepare("SELECT COUNT(*) AS n FROM document_jobs").get().n,1,"guard checks do not submit replacement jobs");
});
